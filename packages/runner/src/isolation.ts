import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import type { CredentialProfile, HarnessType, SkillMountSpec } from "@ade/shared";

export type AdeMode = "solo" | "team" | "vps";

export class RunnerDomainError extends Error {
  constructor(
    public readonly code: string,
    message: string,
    public readonly httpStatus = 400
  ) {
    super(message);
    this.name = "RunnerDomainError";
  }
}

export function validateCredentialForMode(
  profile: CredentialProfile,
  harness: HarnessType,
  mode: AdeMode
): void {
  if (mode === "vps" && (profile === "sub-claude" || profile === "sub-chatgpt")) {
    throw new RunnerDomainError(
      "ERR_CREDENTIAL_MODE_MISMATCH",
      "Hồ sơ xác thực gói thuê bao không được phép trong chế độ VPS.",
      400
    );
  }
  if (profile === "sub-claude" && harness !== "claude-code") {
    throw new RunnerDomainError(
      "ERR_CREDENTIAL_MODE_MISMATCH",
      "Profile sub-claude chỉ dùng cho harness claude-code.",
      400
    );
  }
  if (profile === "sub-chatgpt" && harness !== "codex") {
    throw new RunnerDomainError(
      "ERR_CREDENTIAL_MODE_MISMATCH",
      "Profile sub-chatgpt chỉ dùng cho harness codex.",
      400
    );
  }
}

export interface IsolationPaths {
  adeRootDir: string;
  claudeConfigDir: string;
  codexHomeDir: string;
  runsDir: string;
}

export class IsolationProfileManager {
  public readonly paths: IsolationPaths;
  private readonly devHomeDir: string;

  constructor(options?: { adeRootDir?: string; devHomeDir?: string }) {
    this.devHomeDir = options?.devHomeDir ?? os.homedir();
    const adeRootDir = options?.adeRootDir ?? path.join(this.devHomeDir, ".ade");
    this.paths = {
      adeRootDir,
      claudeConfigDir: path.join(adeRootDir, "harness", "claude"),
      codexHomeDir: path.join(adeRootDir, "harness", "codex"),
      runsDir: path.join(adeRootDir, "runs")
    };
  }

  async ensureBaseDirs(): Promise<void> {
    await fs.mkdir(this.paths.claudeConfigDir, { recursive: true });
    await fs.mkdir(this.paths.codexHomeDir, { recursive: true });
    await fs.mkdir(this.paths.runsDir, { recursive: true });
  }

  buildClaudeEnv(profile: CredentialProfile, baseEnv: NodeJS.ProcessEnv = process.env): Record<string, string> {
    const env: Record<string, string> = {};
    for (const [k, v] of Object.entries(baseEnv)) {
      if (typeof v === "string" && k !== "ANTHROPIC_API_KEY") {
        env[k] = v;
      }
    }
    env.CLAUDE_CONFIG_DIR = this.paths.claudeConfigDir;
    env.CLAUDE_CODE_DISABLE_AUTO_MEMORY = "1";
    if (profile === "api-key" && baseEnv.ADE_ANTHROPIC_API_KEY) {
      env.ANTHROPIC_API_KEY = baseEnv.ADE_ANTHROPIC_API_KEY;
    }
    return env;
  }

  async createTempClaudePlugin(runId: string, skills: SkillMountSpec[]): Promise<string> {
    await this.ensureBaseDirs();
    const pluginDir = path.join(this.paths.runsDir, runId, "plugin");
    const manifestDir = path.join(pluginDir, ".claude-plugin");
    await fs.mkdir(manifestDir, { recursive: true });
    await fs.writeFile(
      path.join(manifestDir, "plugin.json"),
      JSON.stringify(
        {
          name: `ade-run-${runId}`,
          version: "1.0.0",
          description: "Temporary isolated skill bundle generated by ADE"
        },
        null,
        2
      ),
      "utf8"
    );

    const skillsOutDir = path.join(pluginDir, "skills");
    await fs.mkdir(skillsOutDir, { recursive: true });
    for (const skill of skills) {
      const destSkillDir = path.join(skillsOutDir, skill.name);
      await fs.cp(skill.sourceDir, destSkillDir, { recursive: true });
    }
    return pluginDir;
  }

  async cleanupRunArtifacts(runId: string): Promise<void> {
    const runDir = path.join(this.paths.runsDir, runId);
    await fs.rm(runDir, { recursive: true, force: true });
  }

  async prepareCodexConfigToml(params: {
    model: string | null;
    mcpUrl: string | null;
    mcpToken: string | null;
    writeAllowed: boolean;
  }): Promise<string> {
    await this.ensureBaseDirs();
    // Chỉ quét danh sách tên thư mục con tại ~/.agents/skills (nếu tồn tại) để vô hiệu hoá trong config.toml.
    // Tuyệt đối không đọc nội dung file cá nhân hay ghi bất kỳ thứ gì vào ~/.agents.
    const personalSkillsRoot = path.join(this.devHomeDir, ".agents", "skills");
    const disabledSkillPaths: string[] = [];
    try {
      const entries = await fs.readdir(personalSkillsRoot, { withFileTypes: true });
      for (const entry of entries) {
        if (entry.isDirectory() || entry.isSymbolicLink()) {
          disabledSkillPaths.push(path.join(personalSkillsRoot, entry.name));
        }
      }
    } catch {
      // Thư mục ~/.agents/skills không tồn tại trên máy -> bỏ qua
    }

    const lines: string[] = [];
    if (params.model) {
      lines.push(`model = ${JSON.stringify(params.model)}`);
    }
    lines.push(`sandbox_mode = ${JSON.stringify(params.writeAllowed ? "workspace-write" : "read-only")}`);
    lines.push("");
    if (params.mcpUrl !== null && params.mcpToken !== null) {
      lines.push("[mcp_servers.ade]");
      lines.push(`url = ${JSON.stringify(params.mcpUrl)}`);
      lines.push(`http_headers = { Authorization = ${JSON.stringify(`Bearer ${params.mcpToken}`)} }`);
      lines.push("");
    }

    for (const skillPath of disabledSkillPaths) {
      lines.push("[[skills.config]]");
      lines.push(`path = ${JSON.stringify(skillPath)}`);
      lines.push("enabled = false");
      lines.push("");
    }

    const configPath = path.join(this.paths.codexHomeDir, "config.toml");
    await fs.writeFile(configPath, lines.join("\n"), "utf8");
    return configPath;
  }

  buildCodexEnv(profile: CredentialProfile, baseEnv: NodeJS.ProcessEnv = process.env): Record<string, string> {
    const env: Record<string, string> = {};
    for (const [k, v] of Object.entries(baseEnv)) {
      if (typeof v === "string" && k !== "OPENAI_API_KEY") {
        env[k] = v;
      }
    }
    env.CODEX_HOME = this.paths.codexHomeDir;
    if (profile === "api-key" && baseEnv.ADE_OPENAI_API_KEY) {
      env.OPENAI_API_KEY = baseEnv.ADE_OPENAI_API_KEY;
    }
    return env;
  }
}
